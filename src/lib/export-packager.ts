import JSZip from 'jszip';
import { saveAs } from 'file-saver';
import { EnginePreset, PBRMaps } from '../types';

function dataURLToBlob(dataURL: string): Blob {
  const arr = dataURL.split(',');
  const mime = arr[0].match(/:(.*?);/)![1];
  const bstr = atob(arr[1]);
  let n = bstr.length;
  const u8arr = new Uint8Array(n);
  while (n--) {
    u8arr[n] = bstr.charCodeAt(n);
  }
  return new Blob([u8arr], { type: mime });
}

export async function packageAndDownloadTextures(
  maps: PBRMaps,
  materialName: string,
  engine: EnginePreset = 'unity'
) {
  const zip = new JSZip();
  const folder = zip.folder(materialName || 'PBR_Material')!;

  // 1. Albedo
  folder.file(`${materialName}_Albedo.png`, dataURLToBlob(maps.albedo));

  // 2. Normal
  folder.file(`${materialName}_Normal.png`, dataURLToBlob(maps.normal));

  // 3. Roughness
  folder.file(`${materialName}_Roughness.png`, dataURLToBlob(maps.roughness));

  // 4. Height / Displacement
  folder.file(`${materialName}_Height.png`, dataURLToBlob(maps.height));

  // 5. Ambient Occlusion
  folder.file(`${materialName}_AO.png`, dataURLToBlob(maps.ao));

  // 6. Unreal Engine Packed ORM
  if (maps.orm && (engine === 'ue5' || engine === 'raw')) {
    folder.file(`${materialName}_ORM_Packed.png`, dataURLToBlob(maps.orm));
  }

  // 7. Engine Setup Instructions Readme
  let readme = `=== ${materialName.toUpperCase()} PBR MATERIAL PACKAGE ===\n`;
  readme += `Generated by TextureForge AI (SaaS for Indie Game Developers)\n\n`;

  if (engine === 'unity') {
    readme += `[UNITY URP / HDRP SETUP]:\n`;
    readme += `1. Drag textures into your Unity Assets folder.\n`;
    readme += `2. Select "${materialName}_Normal.png", in Inspector set "Texture Type" to "Normal map", click Apply.\n`;
    readme += `3. Create a new Material (Shader: Universal Render Pipeline/Lit).\n`;
    readme += `4. Assign:\n`;
    readme += `   - Base Map -> ${materialName}_Albedo.png\n`;
    readme += `   - Normal Map -> ${materialName}_Normal.png\n`;
    readme += `   - Metallic/Smoothness -> Invert Roughness or use Mask Map.\n`;
    readme += `   - Occlusion -> ${materialName}_AO.png\n`;
  } else if (engine === 'ue5') {
    readme += `[UNREAL ENGINE 5 SETUP]:\n`;
    readme += `1. Drag all textures into the Content Browser.\n`;
    readme += `2. Open "${materialName}_ORM_Packed.png", UNCHECK "sRGB" (Linear Color).\n`;
    readme += `3. In your Material Editor:\n`;
    readme += `   - Albedo -> Base Color\n`;
    readme += `   - Normal -> Normal\n`;
    readme += `   - ORM Packed Map:\n`;
    readme += `       * Red channel -> Ambient Occlusion\n`;
    readme += `       * Green channel -> Roughness\n`;
    readme += `       * Blue channel -> Metallic\n`;
  } else if (engine === 'godot') {
    readme += `[GODOT 4 SETUP]:\n`;
    readme += `1. Add textures to your Godot project folder.\n`;
    readme += `2. Create a StandardMaterial3D.\n`;
    readme += `3. Assign:\n`;
    readme += `   - Albedo -> Texture: ${materialName}_Albedo.png\n`;
    readme += `   - Roughness -> Texture: ${materialName}_Roughness.png\n`;
    readme += `   - Normal Map -> Enable, Texture: ${materialName}_Normal.png\n`;
    readme += `   - Ambient Occlusion -> Enable, Texture: ${materialName}_AO.png\n`;
  } else if (engine === 'blender') {
    readme += `[BLENDER PRINCIPLED BSDF SETUP]:\n`;
    readme += `1. In Shader Editor, enable Node Wrangler (Ctrl+Shift+T on Principled BSDF).\n`;
    readme += `2. Select all files or manually plug:\n`;
    readme += `   - Base Color <- Albedo (sRGB)\n`;
    readme += `   - Roughness <- Roughness (Non-Color)\n`;
    readme += `   - Normal <- Normal Map Node <- Normal (Non-Color)\n`;
    readme += `   - Displacement <- Displacement Node <- Height (Non-Color)\n`;
  }

  folder.file('README_ENGINE_SETUP.txt', readme);

  // Generate ZIP
  const content = await zip.generateAsync({ type: 'blob' });
  saveAs(content, `${materialName}_${engine}_PBR_Textures.zip`);
}
